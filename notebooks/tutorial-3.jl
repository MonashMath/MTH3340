# ╔═╡ 1a2b3c4d-5e6f-4a7b-8c9d-0e1f2a3b4c29
md"## Watching the two schemes in time

A single snapshot hides the dynamics, and the interesting part is the beginning: the first few steps, in which the box is smoothed out. Below, the two schemes are run from the box with $\tau = 2.5 \cdot 10^{-3}$, i.e. $\mu\tau/h^2 = 1$, up to $T = 0.05$; every time step is a frame of the animation, shown at two frames per second (`Plots.@animate` builds it, `gif` encodes it, Pluto shows the result inline). Watch how backward Euler rounds off the corners of the box within two or three steps, and how the Crank–Nicolson oscillations, born at the two jumps, change sign from one step to the next and decay only slowly.

The reason is worth knowing. For a mode of the mesh with eigenvalue $\lambda$ of $M^{-1}K$, one step of the $\theta$-method multiplies its amplitude by $(1 - (1-\theta)\tau\lambda)/(1 + \theta\tau\lambda)$. For backward Euler this is $1/(1+\tau\lambda) \to 0$ as $\tau\lambda \to \infty$: stiff modes are killed. For Crank–Nicolson it is $(1 - \tau\lambda/2)/(1 + \tau\lambda/2) \to -1$: stiff modes are *not* damped, they just flip sign. Here the stiffest mode has $\tau\lambda_{\max} = 12\mu\tau/h^2 = 12$: backward Euler multiplies it by $1/13$ per step, Crank–Nicolson by $-5/7$. Both are stable ($|\cdot| \le 1$), only one is dissipative."

# ╔═╡ 2b3c4d5e-6f7a-4b8c-9d0e-1f2a3b4c5d30
begin
  _, ts_anim, _, frames_be = solve_heat(1.0, 2.5e-3, 0.05, box)
  _, _, _, frames_cn = solve_heat(0.5, 2.5e-3, 0.05, box)
  anim_schemes = @animate for i in eachindex(ts_anim)
    plot(xs, box.(Point.(xs)); label="u⁰", color=:gray, linestyle=:dash, ylims=(-0.1, 1.1))
    plot!(xs, frames_be[i]; label="backward Euler", linewidth=2)
    plot!(xs, frames_cn[i]; label="Crank–Nicolson", linewidth=2)
    plot!(xlabel="x", ylabel="u_h", legend=:topright,
          title="τ = 2.5·10⁻³,  t = $(round(ts_anim[i], digits=4))")
  end
  gif(anim_schemes; fps=2)
end

# ╔═╡ a3b4c5d6-e7f8-4a9b-0c1d-2e3f4a5b6c16
md"# Test 2: forward Euler and the CFL condition

**Objective:** observe that an explicit scheme is stable only for small enough time steps.

**Description:** Lemma 5.4.4 proves stability of forward Euler under $\tau < h^2/(C_{inv}^2 \mu)$. For $\mathcal{P}_1$ elements in 1D with the consistent mass matrix, the sharp value of the constant is $6$: the scheme is stable if and only if $\tau \le h^2/6$, here $\approx 4.2 \cdot 10^{-4}$. We integrate the box initial condition with two time steps, one just below and one just above the limit."

