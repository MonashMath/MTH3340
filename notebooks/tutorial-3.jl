md"# _Tutorial 3: The heat equation with `Gridap.ODEs`_

In this tutorial we discretise the heat equation with the **method of lines**
(Chapter 5): finite elements in space, the $\theta$-method in time. We will

1. solve the model problem of the lectures with backward Euler, Crank–Nicolson and forward Euler, and look at what each scheme does to a rough initial condition;
2. see the **CFL condition** of forward Euler at work;
3. measure the **order in time** of backward Euler and Crank–Nicolson.

Everything is done with the transient machinery of `Gridap` (`Gridap.ODEs`), in the same minimal style as the `Gridap` tutorials: define the spaces, write the weak form, pick a time integrator, iterate over the time steps."

# ╔═╡ a1b2c3d4-e5f6-4a7b-8c9d-0e1f2a3b4c04
md"## The model problem

We take the problem of the lectures: $\Omega = (0,1)$, $\mu = 1$, homogeneous Dirichlet conditions,

$$\partial_t u - u'' = f \quad \text{in } (0,1) \times (0,T], \qquad u(0,t) = u(1,t) = 0, \qquad u(x,0) = u^0(x).$$

Space is discretised with $\mathcal{P}_1$ finite elements on a uniform mesh of $N$ cells. Let us build the mesh and the spaces as in Tutorial 1. The only novelty is the trial space: since Dirichlet data may depend on time, `Gridap` asks for it as a function of $t$ returning a function of $x$, and the space is a `TransientTrialFESpace`."

# ╔═╡ b2c3d4e5-f6a7-4b8c-9d0e-1f2a3b4c5d05
begin
  N = 20
  h = 1 / N
  μ = 1.0
  model = CartesianDiscreteModel((0.0, 1.0), (N,))
  reffe = ReferenceFE(lagrangian, Float64, 1)
  V = TestFESpace(model, reffe; conformity=:H1, dirichlet_tags="boundary")
  g(x, t::Real) = 0.0
  g(t::Real) = x -> g(x, t)
  U = TransientTrialFESpace(V, g)
  Ω = Triangulation(model)
  dΩ = Measure(Ω, 2)
  dΩe = Measure(Ω, 6)   # finer quadrature, for errors only
end

# ╔═╡ c3d4e5f6-a7b8-4c9d-0e1f-2a3b4c5d6e06
md"## The transient weak form

At each time $t$, the semi-discrete problem reads: find $u_h(t) \in V_h$ such that

$$\underbrace{\int_\Omega \partial_t u_h\, v_h}_{m(\partial_t u_h, v_h)} + \underbrace{\int_\Omega \mu \nabla u_h \cdot \nabla v_h}_{a(u_h, v_h)} = \underbrace{\int_\Omega f v_h}_{l(v_h)} \qquad \forall v_h \in V_h,$$

which is the ODE system $M \dot U + K U = F$ of the notes. In `Gridap` we write the three forms as functions of $t$ (they could depend on it), and pass them to a `TransientLinearFEOperator`. The forms are given **in order of the time derivative they multiply**: the stiffness form (order 0) first, the mass form (order 1) second. Since neither depends on $t$, we tell `Gridap` so with `constant_forms`, and the matrices are assembled once."

# ╔═╡ d4e5f6a7-b8c9-4d0e-1f2a-3b4c5d6e7f07
begin
  m(t, dtu, v) = ∫(dtu * v)dΩ
  a(t, u, v) = ∫(μ * ∇(u) ⋅ ∇(v))dΩ
  make_operator(f) = TransientLinearFEOperator(a, m, (t, v) -> ∫(f(t) * v)dΩ, U, V;
                                               constant_forms=(true, true))
end

# ╔═╡ e5f6a7b8-c9d0-4e1f-2a3b-4c5d6e7f8a08
md"## The $\theta$-method

The time integrator is `ThetaMethod(linear_solver, τ, θ)`: $\theta = 1$ is backward Euler, $\theta = 1/2$ Crank–Nicolson, $\theta = 0$ forward Euler. `solve` returns an **iterator** over the time steps: each iteration hands back the pair `(t, uh)`. That is time marching in code: the solution at $t_{i+1}$ is computed from the one at $t_i$ and nothing else is stored.

To plot a finite element function in 1D we simply evaluate it at a fine set of points."

# ╔═╡ b8c9d0e1-f2a3-4b4c-5d6e-7f8a9b0c1d11
begin
  xs = range(0.0, 1.0; length=201)
  evalfe(uh) = [uh(Point(x)) for x in xs]
end

# ╔═╡ a7b8c9d0-e1f2-4a3b-4c5d-6e7f8a9b0c10
md"The function below runs one scheme from $t = 0$ to $t = T$ with step $\tau$, starting from the initial condition `u0`. It returns the solution at the final time, the history of $\|u_h(t_i)\|_{L^2(\Omega)}$, and the values of $u_h(t_i)$ at the plotting points (one *frame* per time step, for the animations below)."

# ╔═╡ f6a7b8c9-d0e1-4f2a-3b4c-5d6e7f8a9b09
function solve_heat(θ, τ, T, u0; f = t -> (x -> 0.0))
  op = make_operator(f)
  solver = ThetaMethod(LUSolver(), τ, θ)
  uh0 = interpolate_everywhere(u0, U(0.0))
  l2(w) = sqrt(sum(∫(w * w)dΩ))
  ts = [0.0]
  norms = [l2(uh0)]
  frames = [evalfe(uh0)]
  uhT = uh0
  for (t, uh) in solve(solver, op, 0.0, T, uh0)
    push!(ts, t)
    push!(norms, l2(uh))
    push!(frames, evalfe(uh))
    uhT = uh
  end
  return uhT, ts, norms, frames
end

# ╔═╡ c9d0e1f2-a3b4-4c5d-6e7f-8a9b0c1d2e12
md"# Test 1: three schemes, one rough initial condition

**Objective:** see the qualitative behaviour of the three members of the $\theta$-family.

**Description:** we start from the box $u^0 = \chi_{(0.25,0.75)}$ (a discontinuous function: the heat equation smooths it instantly) with $f = 0$, and integrate up to $T = 0.02$ with $\tau = 10^{-2}$, i.e. two time steps, using backward Euler and Crank–Nicolson."

# ╔═╡ d0e1f2a3-b4c5-4d6e-7f8a-9b0c1d2e3f13
box(x) = (0.25 < x[1] < 0.75) ? 1.0 : 0.0

# ╔═╡ e1f2a3b4-c5d6-4e7f-8a9b-0c1d2e3f4a14
begin
  uh_be, _, _, _ = solve_heat(1.0, 0.01, 0.02, box)
  uh_cn, _, _, _ = solve_heat(0.5, 0.01, 0.02, box)
  plot(xs, box.(Point.(xs)); label="u⁰", color=:gray, linestyle=:dash)
  plot!(xs, evalfe(uh_be); label="backward Euler", marker=:circle, markersize=2)
  plot!(xs, evalfe(uh_cn); label="Crank–Nicolson", marker=:circle, markersize=2)
  plot!(xlabel="x", ylabel="u_h", title="τ = 0.01, t = 0.02", legend=:topright)
end

# ╔═╡ f2a3b4c5-d6e7-4f8a-9b0c-1d2e3f4a5b15
md"Two steps of the same size, two very different solutions.

- **Backward Euler** has erased the jumps: the solution is already a smooth bump. This is the *numerical dissipation* of the scheme, the extra term $\sum_i \|U^i - U^{i-1}\|_M^2$ in its stability bound (Lemma 5.4.1). It damps whatever the equation does not resolve, which is robust but not accurate: the true solution at $t = 0.02$ is not this smooth.
- **Crank–Nicolson** is stable (nothing grows) but has no numerical dissipation (Lemma 5.4.3): the jumps of $u^0$ *ring* around $x = 0.25$ and $x = 0.75$, and these oscillations decay very slowly. Second order in time buys accuracy on smooth solutions, not robustness on rough data.

