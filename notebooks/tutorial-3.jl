# ╔═╡ a9b0c1d2-e3f4-4a5b-6c7d-8e9f0a1b2c22
md"# Test 3: order of convergence in time

**Objective:** verify the orders $\tau^1$ (backward Euler) and $\tau^2$ (Crank–Nicolson) of Theorem 5.5.1.

**Description:** we need an exact solution. With $\mu = 1$ and $f = 0$,

$$u(x,t) = \sin(\pi x)\, e^{-\pi^2 t}$$

solves the heat equation with homogeneous Dirichlet data. The total error is $C(h^{r+1} + \tau^\beta)$: to see the order in $\tau$ we must make the spatial error negligible, so we use a much finer mesh, $N = 400$, and measure $\|u(T) - u_h^M\|_{L^2(\Omega)}$ at $T = 0.1$ for $\tau = 0.02, 0.01, 0.005, 0.0025$."

# ╔═╡ b0c1d2e3-f4a5-4b6c-7d8e-9f0a1b2c3d23
uex(t) = x -> sin(π * x[1]) * exp(-π^2 * t)

# ╔═╡ c1d2e3f4-a5b6-4c7d-8e9f-0a1b2c3d4e24
md"The function below repeats the set-up on a mesh of `Nc` cells (the spaces of the previous sections are tied to `N = 20`) and returns the $L^2$ error at $T$ for a given $\theta$ and $\tau$. Note the finer quadrature for the error, as in Tutorial 2."

# ╔═╡ d2e3f4a5-b6c7-4d8e-9f0a-1b2c3d4e5f25
function time_error(θ, τ, T, Nc)
  mdl = CartesianDiscreteModel((0.0, 1.0), (Nc,))
  Vc = TestFESpace(mdl, reffe; conformity=:H1, dirichlet_tags="boundary")
  Uc = TransientTrialFESpace(Vc, g)
  Ωc = Triangulation(mdl)
  dΩc = Measure(Ωc, 2)
  dΩce = Measure(Ωc, 6)
  mc(t, dtu, v) = ∫(dtu * v)dΩc
  ac(t, u, v) = ∫(μ * ∇(u) ⋅ ∇(v))dΩc
  lc(t, v) = ∫(0.0 * v)dΩc
  op = TransientLinearFEOperator(ac, mc, lc, Uc, Vc; constant_forms=(true, true))
  solver = ThetaMethod(LUSolver(), τ, θ)
  uh0 = interpolate_everywhere(uex(0.0), Uc(0.0))
  tT, uhT = 0.0, uh0
  for (t, uh) in solve(solver, op, 0.0, T, uh0)
    tT, uhT = t, uh
  end
  e = uex(tT) - uhT
  return sqrt(sum(∫(e * e)dΩce))
end

# ╔═╡ e3f4a5b6-c7d8-4e9f-0a1b-2c3d4e5f6a26
begin
  τs = [0.02, 0.01, 0.005, 0.0025]
  err_be = [time_error(1.0, τ, 0.1, 400) for τ in τs]
  err_cn = [time_error(0.5, τ, 0.1, 400) for τ in τs]
  rate(e) = [log(e[i] / e[i+1]) / log(2) for i in 1:length(e)-1]
  (BE=err_be, BE_rates=rate(err_be), CN=err_cn, CN_rates=rate(err_cn))
end

# ╔═╡ f4a5b6c7-d8e9-4f0a-1b2c-3d4e5f6a7b27
begin
  plot(τs, err_be; label="backward Euler", marker=:circle, xaxis=:log, yaxis=:log)
  plot!(τs, err_cn; label="Crank–Nicolson", marker=:square)
  plot!(τs, err_be[1] .* (τs ./ τs[1]); label="slope 1", linestyle=:dash, color=:gray)
  plot!(τs, err_cn[1] .* (τs ./ τs[1]) .^ 2; label="slope 2", linestyle=:dot, color=:gray)
  plot!(xlabel="τ", ylabel="‖u(T) − u_h^M‖_{L²}", legend=:bottomright, title="N = 400, T = 0.1")
end

