md"Below $h^2/6$ the norm decays, as it must. Above it, the norm grows exponentially: at $t = 0.01$ (20 steps with $\tau = 5 \cdot 10^{-4}$) the norm is already more than ten times too large, and the growth is exponential: a few more steps and it is off by orders of magnitude. Just above the limit ($\tau = 4.5 \cdot 10^{-4}$) the growth factor per step is barely above one, so the instability takes longer to show, but it is there. Nothing in between: the CFL condition is a threshold, not a gradual loss of accuracy.

