# ╔═╡ d6e7f8a9-b0c1-4d2e-3f4a-5b6c7d8e9f19
md"Just above the limit, a node-to-node oscillation appears and grows at every step: the highest-frequency mode of the mesh is amplified by a factor larger than one. The cleanest way to see the threshold is to look at the $L^2$ norm of the solution as a function of time: for the heat equation it must decrease."

